def token(name: str) -> tuple[int, int, int]:
    m = re.search(rf'--{name}:\s*#([0-9a-fA-F]{{6}})', (ROOT / 'src/styles/tokens.css').read_text(encoding='utf8'))
    if not m:
        raise SystemExit(f'--{name} not found in src/styles/tokens.css')
    return tuple(int(m.group(1)[i:i + 2], 16) for i in (0, 2, 4))


SIGNAL, VOID = token('signal'), token('void')
DIM = tuple(round(0.55 * s + 0.45 * v) for s, v in zip(SIGNAL, VOID))  # the hardware: signal at 55 % on the void


def from_grid(grid: list[str]) -> Image.Image:
    n = len(grid)
    assert all(len(row) == n for row in grid), 'a grid is square'
    ink = {'#': SIGNAL, '+': DIM, '.': VOID}
    im = Image.new('RGBA', (n, n))
    im.putdata([ink[c] + (255,) for row in grid for c in row])
    return im


def font(file: str, axes: dict, size: int) -> ImageFont.FreeTypeFont:
    f = TTFont(ROOT / 'public/fonts' / file)
    f.flavor = None
    out = io.BytesIO()
    instancer.instantiateVariableFont(f, axes).save(out)
    out.seek(0)
    return ImageFont.truetype(out, size)


def grain(im: Image.Image, seed: int = 0xC8FF00, spread: int = 60, opacity: float = 0.42) -> Image.Image:
    """The site's grain, baked once: a 128-centred noise texel per pixel, overlaid. Over the void it is a no-op."""
    rnd = random.Random(seed)
    px = im.load()
    for y in range(im.height):
        for x in range(im.width):
            s = int(128 + (rnd.random() * 2 - 1) * spread) / 255
            out = []
            for c in px[x, y]:
                b = c / 255
                o = 2 * b * s if b < 0.5 else 1 - 2 * (1 - b) * (1 - s)
                out.append(round(255 * (b + opacity * (o - b))))
            px[x, y] = tuple(out)
    return im


def touch_icon(n: int = 180, ss: int = 8) -> Image.Image:
    """The home-screen icon on a 60-unit plate (1 unit = 3 px at 180), drawn at 8x and brought down."""
    s = n * ss
    u = s / 60
    im = Image.new('RGB', (s, s), VOID)
    d = ImageDraw.Draw(im)

    def box(x0, y0, x1, y1, ink):
        d.rectangle([round(x0 * u), round(y0 * u), round(x1 * u) - 1, round(y1 * u) - 1], fill=ink)

    for cx, cy in ((8, 8), (52, 8), (8, 52), (52, 52)):  # the registration crosses, clear of iOS's corner mask
        box(cx - 3.5, cy - 0.5, cx + 3.5, cy + 0.5, DIM)
        box(cx - 0.5, cy - 3.5, cx + 0.5, cy + 3.5, DIM)
    for x in range(14, 46, 2):  # the tick rail, on the bottom crosses' line
        box(x, 51, x + 1, 53, DIM)
    code = font('MartianMono-Var.woff2', {'wght': 500, 'wdth': 112.5}, round(3.2 * u / 0.72))
    l, t, r, b = d.textbbox((0, 0), 'RVL', font=code)  # the code, on the top crosses' line
    d.text((s / 2 - (l + r) / 2, 8 * u - (t + b) / 2), 'RVL', font=code, fill=DIM)

    cap = 26 * u  # R.: Bodoni Moda's cap height is 0.75 em
    serif = font('BodoniModa-Var.woff2', {'wght': 700, 'opsz': 32}, round(cap / 0.75))
    rl, _, rr, _ = d.textbbox((0, 0), 'R', font=serif)
    pl, _, pr, _ = d.textbbox((0, 0), '.', font=serif)
    gap = 1.6 * u  # the period tucked in, closer than the font sets it
    x0 = s / 2 - (rr - rl + gap + pr - pl) / 2
    top = 30 * u + cap / 2 - serif.getmetrics()[0]  # baseline 13 units under the plate's centre
    d.text((x0 - rl, top), 'R', font=serif, fill=SIGNAL)
    d.text((x0 + rr - rl + gap - pl, top), '.', font=serif, fill=SIGNAL)
    return grain(im.resize((n, n), Image.LANCZOS))


def ico(frames: list[Image.Image]) -> bytes:
    """An .ico of PNG frames (every browser, and Windows since Vista)."""
    pngs = []
    for im in frames:
        b = io.BytesIO()
        im.save(b, 'PNG', optimize=True)
        pngs.append(b.getvalue())
    head = struct.pack('<HHH', 0, 1, len(frames))
    at = 6 + 16 * len(frames)
    entries = b''
    for im, png in zip(frames, pngs):
        entries += struct.pack('<BBBBHHII', im.width % 256, im.height % 256, 0, 0, 1, 32, len(png), at)
        at += len(png)
    return head + entries + b''.join(pngs)


